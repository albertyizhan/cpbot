CREATE SCHEMA cpbot;
SET LOCAL search_path = cpbot, pg_catalog;

CREATE TABLE clusters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name text NOT NULL
);
CREATE TABLE cluster_authorizations (
    cluster_id bigint PRIMARY KEY REFERENCES clusters(id)
);
CREATE TABLE cluster_activation_codes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    code_hash text NOT NULL UNIQUE,
    expires double precision NOT NULL,
    redeemed double precision,
    revoked integer NOT NULL DEFAULT 0
);
CREATE INDEX cluster_activation_pending ON cluster_activation_codes(cluster_id)
    WHERE redeemed IS NULL AND revoked = 0;
CREATE TABLE chat_ownership (
    chat_id bigint PRIMARY KEY CHECK (chat_id < 0),
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    UNIQUE (cluster_id, chat_id)
);
CREATE TABLE cluster_management_groups (
    cluster_id bigint PRIMARY KEY,
    chat_id bigint NOT NULL,
    title text NOT NULL,
    FOREIGN KEY (cluster_id, chat_id) REFERENCES chat_ownership(cluster_id, chat_id)
);
CREATE TABLE membership_targets (
    cluster_id bigint PRIMARY KEY,
    chat_id bigint NOT NULL,
    title text NOT NULL,
    FOREIGN KEY (cluster_id, chat_id) REFERENCES chat_ownership(cluster_id, chat_id)
);
CREATE TABLE settings (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    key text NOT NULL,
    value text NOT NULL,
    PRIMARY KEY (cluster_id, key)
);
CREATE TABLE people (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint,
    username text,
    name text NOT NULL DEFAULT '',
    observed double precision NOT NULL DEFAULT 0,
    tags text NOT NULL DEFAULT '',
    version bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (cluster_id, id),
    UNIQUE (cluster_id, user_id)
);
CREATE UNIQUE INDEX people_username ON people(cluster_id, lower(username COLLATE "C"));
CREATE INDEX people_name ON people(cluster_id, name);
CREATE TABLE memberships (
    cluster_id bigint NOT NULL,
    person bigint NOT NULL,
    chat_id bigint NOT NULL,
    title text NOT NULL,
    joined double precision,
    present integer,
    observed double precision NOT NULL,
    PRIMARY KEY (cluster_id, person, chat_id),
    FOREIGN KEY (cluster_id, person) REFERENCES people(cluster_id, id)
);
CREATE TABLE history (
    cluster_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    person bigint NOT NULL,
    actor bigint NOT NULL,
    actor_name text NOT NULL,
    action text NOT NULL,
    before_value text NOT NULL,
    after_value text NOT NULL,
    created double precision NOT NULL,
    PRIMARY KEY (cluster_id, id),
    FOREIGN KEY (cluster_id, person) REFERENCES people(cluster_id, id)
);
CREATE INDEX history_person_id ON history(cluster_id, person, id);
CREATE TABLE teachers (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    user_id bigint,
    username text,
    deleted_at double precision,
    PRIMARY KEY (cluster_id, id),
    UNIQUE (cluster_id, user_id)
);
CREATE UNIQUE INDEX teachers_username ON teachers(cluster_id, lower(username COLLATE "C"));
CREATE TABLE drafts (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    user_id bigint NOT NULL,
    data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
    token text NOT NULL,
    PRIMARY KEY (cluster_id, user_id)
);
CREATE TABLE reviews (
    cluster_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    author bigint NOT NULL,
    identity jsonb NOT NULL CHECK (jsonb_typeof(identity) = 'object'),
    teacher bigint NOT NULL,
    data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object'),
    anonymous integer NOT NULL,
    status text NOT NULL,
    manual integer NOT NULL DEFAULT 0,
    created double precision NOT NULL,
    expires double precision,
    submission text NOT NULL,
    version bigint NOT NULL DEFAULT 1,
    PRIMARY KEY (cluster_id, id),
    UNIQUE (cluster_id, submission),
    FOREIGN KEY (cluster_id, teacher) REFERENCES teachers(cluster_id, id)
);
CREATE INDEX reviews_teacher_time ON reviews(cluster_id, teacher, status, (data ->> '时间'), id);
CREATE INDEX reviews_author_created ON reviews(cluster_id, author, created DESC);
CREATE INDEX reviews_expiry ON reviews(cluster_id, expires) WHERE status IN ('pending', 'rejected');
CREATE TABLE codes (
    cluster_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    teacher bigint NOT NULL,
    value text NOT NULL,
    state text NOT NULL DEFAULT 'open',
    created double precision NOT NULL,
    used_review bigint,
    PRIMARY KEY (cluster_id, id),
    FOREIGN KEY (cluster_id, teacher) REFERENCES teachers(cluster_id, id)
);
CREATE UNIQUE INDEX open_code ON codes(cluster_id, teacher, value) WHERE state = 'open';
CREATE TABLE bindings (
    cluster_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    mode text NOT NULL,
    chat_id bigint NOT NULL,
    discussion bigint,
    title text NOT NULL,
    active integer NOT NULL DEFAULT 1,
    error text NOT NULL DEFAULT '',
    PRIMARY KEY (cluster_id, id),
    UNIQUE (chat_id),
    UNIQUE (discussion),
    FOREIGN KEY (cluster_id, chat_id) REFERENCES chat_ownership(cluster_id, chat_id),
    FOREIGN KEY (cluster_id, discussion) REFERENCES chat_ownership(cluster_id, chat_id)
);
CREATE TABLE posts (
    cluster_id bigint NOT NULL,
    binding bigint NOT NULL,
    teacher bigint NOT NULL,
    message bigint,
    root bigint,
    generation bigint NOT NULL DEFAULT 1,
    PRIMARY KEY (cluster_id, binding, teacher),
    FOREIGN KEY (cluster_id, binding) REFERENCES bindings(cluster_id, id)
);
CREATE TABLE publications (
    cluster_id bigint NOT NULL,
    binding bigint NOT NULL,
    review bigint NOT NULL,
    generation bigint NOT NULL,
    message bigint NOT NULL,
    chat_id bigint NOT NULL,
    PRIMARY KEY (cluster_id, binding, review, generation),
    FOREIGN KEY (cluster_id, review) REFERENCES reviews(cluster_id, id)
);
CREATE INDEX publications_review ON publications(cluster_id, review, binding, generation);
CREATE TABLE proof_publications (
    cluster_id bigint NOT NULL,
    binding bigint NOT NULL,
    review bigint NOT NULL,
    generation bigint NOT NULL,
    message bigint NOT NULL,
    chat_id bigint NOT NULL,
    PRIMARY KEY (cluster_id, binding, review, generation),
    FOREIGN KEY (cluster_id, review) REFERENCES reviews(cluster_id, id)
);
CREATE TABLE jobs (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    kind text NOT NULL,
    binding bigint NOT NULL,
    teacher bigint NOT NULL,
    review bigint NOT NULL DEFAULT 0,
    generation bigint NOT NULL DEFAULT 1,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'sending', 'done', 'blocked', 'uncertain', 'superseded')),
    due double precision NOT NULL DEFAULT 0,
    error text NOT NULL DEFAULT '',
    attempt_generation bigint,
    PRIMARY KEY (cluster_id, id),
    UNIQUE (cluster_id, kind, binding, teacher, review, generation)
);
CREATE INDEX jobs_pending_due ON jobs(cluster_id, due, binding) WHERE state = 'pending';
CREATE INDEX jobs_open_review ON jobs(cluster_id, binding, teacher, generation, review)
    WHERE state NOT IN ('done', 'superseded');
CREATE TABLE audit (
    cluster_id bigint NOT NULL REFERENCES clusters(id),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    actor bigint NOT NULL,
    action text NOT NULL,
    detail text NOT NULL,
    created double precision NOT NULL,
    PRIMARY KEY (cluster_id, id)
);
CREATE TABLE schema_version (
    version integer PRIMARY KEY,
    migrated_at timestamptz NOT NULL DEFAULT now()
);
